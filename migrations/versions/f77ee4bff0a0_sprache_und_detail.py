def _migrate_notes():
    conn = op.get_bind()
    movements = sa.table("movements", sa.column("id", sa.Integer), sa.column("action", sa.String),
                         sa.column("note", sa.Text), sa.column("detail", sa.String))
    rows = conn.execute(sa.select(movements.c.id, movements.c.action, movements.c.note)
                        .where(movements.c.action.in_(["nachgerueckt", "befuellt"]))
                        .where(movements.c.note.isnot(None))).fetchall()
    for row_id, action, note in rows:
        detail = None
        if action == "nachgerueckt":
            m = re.match(r"^(K-\d+) wurde darunter entnommen$", note)
            detail = m.group(1) if m else None
        elif note.endswith(" geändert"):
            names = [n.strip() for n in note[:-len(" geändert")].split(",")]
            if all(n in FIELD_KEYS for n in names):
                detail = ",".join(FIELD_KEYS[n] for n in names)
        if detail:
            conn.execute(movements.update().where(movements.c.id == row_id).values(detail=detail, note=None))


